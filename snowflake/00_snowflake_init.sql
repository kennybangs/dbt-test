/* 

Initialize test database for practice

*/

USE ROLE ACCOUNTADMIN;

SHOW USERS;

SHOW WAREHOUSES;

CREATE WAREHOUSE TEST_WH WITH WAREHOUSE_SIZE = 'XSMALL'
  WAREHOUSE_TYPE = 'STANDARD';

CREATE DATABASE TEST_DB;

SHOW GRANTS TO USER SERVICE_DBT;

SHOW GRANTS ON WAREHOUSE TEST_WH;

CREATE ROLE TEST_DBT_ROLE;

GRANT USAGE ON WAREHOUSE TEST_WH TO ROLE TEST_DBT_ROLE;

GRANT ALL ON DATABASE TEST_DB TO ROLE TEST_DBT_ROLE;

SHOW GRANTS ON DATABASE TEST_DB;

GRANT ROLE TEST_DBT_ROLE TO USER KENBANGCOLA;

GRANT ROLE TEST_DBT_ROLE TO USER SERVICE_DBT;
Ddbt debug --config-dir
USE ROLE TEST_DBT_ROLE;

CREATE SCHEMA TEST_DB.TEST_SCHEMA;

SHOW SCHEMAS IN DATABASE TEST_DB;